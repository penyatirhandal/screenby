export type BatteryStatus =
  | 'charging'
  | 'full'
  | 'discharging'
  | 'not_charging'
  | 'unknown';

export type PluggedSource = 'ac' | 'usb' | 'wireless' | 'none';

export interface BatteryState {
  /** 0 - 100, or -1 when the OS does not report a level. */
  level: number;
  charging: boolean;
  status: BatteryStatus;
  plugged: PluggedSource;
  timestamp: number;
}

export type NetworkType = 'wifi' | 'cellular' | 'ethernet' | 'vpn' | 'none';

export interface NetworkState {
  type: NetworkType;
  /** Human readable transport name, e.g. "Wi-Fi" or "Seluler". */
  label: string;
  connected: boolean;
  validated: boolean;
  metered: boolean;
  /** "2G" | "3G" | "4G" | "5G" when the OS grants phone state access, else null. */
  cellularGeneration: string | null;
  operator: string | null;
}

export interface CropState {
  /** Normalised focal point, 0 = left/top edge, 1 = right/bottom edge. */
  fx: number;
  fy: number;
  /** 1 = cover fit, up to MAX_ZOOM. */
  zoom: number;
}

export interface Wallpaper {
  /** Absolute path inside app-private storage (no file:// prefix). */
  path: string;
  /** Pixel dimensions of the stored (already rotated/downscaled) image. */
  width: number;
  height: number;
  crop: CropState;
}

export interface ImportedWallpaper {
  path: string;
  width: number;
  height: number;
}

export interface LauncherApp {
  label: string;
  packageName: string;
  /** Base64 PNG data URI generated by the native launcher bridge. */
  icon?: string | null;
}

export interface WallpaperColors {
  primary: string;
  secondary?: string | null;
  tertiary?: string | null;
}

/** A game pinned to the home screen. Metadata is always user supplied. */
export interface PinnedGame {
  packageName: string;
  /** Label from Android, used as the default and as a fallback. */
  label: string;
  /** Native app icon data URI, refreshed from the OS on each load. */
  icon?: string | null;
  /** Overrides from the Edit form. */
  customLabel?: string;
  customIconPath?: string;
  releaseYear?: string;
  genre?: string;
  developer?: string;
  publisher?: string;
  pinnedAt: number;
  lastPlayedAt?: number;
}

export type FontChoice = 'hack' | 'inter' | 'arial';
export type FontSizeChoice = 'small' | 'normal' | 'large' | 'xlarge';

/** Built-in widgets rendered by React Native. */
export type BuiltinWidget = 'clock' | 'date' | 'music' | 'battery' | 'network';

/** Snapshot of the active Android media session, read by the music widget. */
export interface NowPlayingState {
  hasSession: boolean;
  playing: boolean;
  title: string | null;
  artist: string | null;
  album: string | null;
  albumArtPath: string | null;
  packageName: string | null;
}

/** Layout is stored as 0..1 fractions so it survives rotation. */
export interface DesktopWidgetLayout {
  x: number;
  y: number;
  width: number;
  height: number;
}

export interface BuiltinDesktopWidget extends DesktopWidgetLayout {
  id: string;
  kind: 'builtin';
  widget: BuiltinWidget;
}

export interface AppDesktopWidget extends DesktopWidgetLayout {
  id: string;
  kind: 'appwidget';
  /** ID allocated by Android's AppWidgetHost. */
  appWidgetId: number;
  /** Flattened ComponentName of the widget provider. */
  provider: string;
  label: string;
}

export type DesktopWidgetItem = BuiltinDesktopWidget | AppDesktopWidget;

export interface WidgetProvider {
  provider: string;
  label: string;
}

export interface AddedWidget {
  appWidgetId: number;
  provider: string;
  label: string;
}

export interface LauncherSettings {
  font: FontChoice;
  fontSize: FontSizeChoice;
  /** Kept for migration from older settings. */
  desktopWidgets: BuiltinWidget[];
  desktopItems: DesktopWidgetItem[];
}

export type HomeTab = 'desktop' | 'games';
